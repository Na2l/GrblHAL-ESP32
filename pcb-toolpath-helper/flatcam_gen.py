#!/usr/bin/env python3
"""Generate the PCB wizard project folder (top/bottom/drills/profile .nc)
from Gerber + Excellon files using FlatCAM, then validate it.

    python3 flatcam_gen.py --top F_Cu.gbr --bottom B_Cu.gbr \
        --drill board.drl --outline Edge_Cuts.gbr --out ./projects/3018-board

FlatCAM is NOT bundled (GPLv3): this writes a FlatCAM automation script into
the output folder and runs it with the local FlatCAM installation.  FlatCAM's
API differs between releases; the generated script is written to be editable
and is version-guarded.
"""
import argparse
import os
import subprocess
import sys

TEMPLATE = r'''#!/usr/bin/env python3
# FlatCAM automation script generated by pcb-toolpath-helper/flatcam_gen.py
# Edit the API calls if your FlatCAM version differs (8.x vs 9.x/beta).
import sys
try:
    from flatcam import FlatCAMApp
except Exception as exc:                       # pragma: no cover
    sys.exit("FlatCAM python package not importable: %s" % exc)

APP = FlatCAMApp()
CERTS = %(paths)r
OUT = %(out)r
ISO_DIA = %(iso)r
DRILL_DIA = %(drill)r
FEED = %(feed)r
SPEED = %(speed)r

os.makedirs(OUT, exist_ok=True)

def export(obj, name):
    path = os.path.join(OUT, name)
    APP.export_gcode(path, obj)
    print("wrote", path)

# ---- top copper isolation ------------------------------------------------
top = APP.open_gerber(CERTS["top"]) if CERTS.get("top") else None
if top:
    iso = APP.isolate(top, dia=ISO_DIA, passes=1, overlap=40)
    export(iso, "top.nc")

# ---- bottom copper isolation (mirrored in X) ------------------------------
if CERTS.get("bottom"):
    bot = APP.open_gerber(CERTS["bottom"])
    APP.mirror(bot)
    export(APP.isolate(bot, dia=ISO_DIA, passes=1, overlap=40), "bottom.nc")

# ---- drills --------------------------------------------------------------
if CERTS.get("drill"):
    exc = APP.open_excellon(CERTS["drill"])
    APP.drill(exc, drill_dia=DRILL_DIA, feed=FEED, speed=SPEED)
    export(exc, "drills.nc")

# ---- board outline -------------------------------------------------------
if CERTS.get("outline"):
    outline = APP.open_gerber(CERTS["outline"])
    APP.cutout(outline, dia=ISO_DIA, feed=FEED, speed=SPEED)
    export(outline, "profile.nc")

print("done")
'''


def build_script(args):
    paths = {
        "top": os.path.abspath(args.top) if args.top else None,
        "bottom": os.path.abspath(args.bottom) if args.bottom else None,
        "drill": os.path.abspath(args.drill) if args.drill else None,
        "outline": os.path.abspath(args.outline) if args.outline else None,
    }
    return (TEMPLATE
            .replace("%(paths)r", repr(paths))
            .replace("%(out)r", repr(os.path.abspath(args.out)))
            .replace("%(iso)r", repr(args.isolation_tool))
            .replace("%(drill)r", repr(args.drill_tool))
            .replace("%(feed)r", repr(args.feed))
            .replace("%(speed)r", repr(args.speed)))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--top")
    ap.add_argument("--bottom")
    ap.add_argument("--drill")
    ap.add_argument("--outline")
    ap.add_argument("--out", required=True)
    ap.add_argument("--isolation-tool", type=float, default=0.2,
                    help="V-bit diameter in mm (default 0.2)")
    ap.add_argument("--drill-tool", type=float, default=0.8)
    ap.add_argument("--feed", type=float, default=200.0)
    ap.add_argument("--speed", type=float, default=10000.0)
    ap.add_argument("--dry-run", action="store_true",
                    help="only write the FlatCAM script")
    args = ap.parse_args()

    if not any([args.top, args.bottom, args.drill, args.outline]):
        sys.exit("give at least one of --top/--bottom/--drill/--outline")

    os.makedirs(args.out, exist_ok=True)
    script = os.path.join(args.out, "run_flatcam.py")
    with open(script, "w", encoding="utf-8") as fh:
        fh.write(build_script(args))
    print("wrote", script)

    if args.dry_run:
        return 0

    try:
        subprocess.run([sys.executable, script], check=True, cwd=args.out)
    except subprocess.CalledProcessError as exc:
        print("FlatCAM run failed (%s). Fix the generated script or run it on "
              "a machine with FlatCAM installed." % exc)
        return 1

    helper = os.path.dirname(os.path.abspath(__file__))
    return subprocess.call([sys.executable, os.path.join(helper, "verify.py"), args.out])


if __name__ == "__main__":
    sys.exit(main())
