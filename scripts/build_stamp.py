# Writes main/build_stamp.h with build time (with timezone) and git info.
# The app descriptor's date/time is only refreshed by full recompiles, so this
# gives the UI an accurate build stamp on every build.
Import("env")

import os
import subprocess
import time

project = env.subst("$PROJECT_DIR")
path = os.path.join(project, "main", "build_stamp.h")

now = time.strftime("%b %d %Y %H:%M:%S")
tz = time.strftime("%Z") or "UTC"
try:
    offset = time.strftime("%z")
except Exception:
    offset = ""
stamp = now + " " + tz + (" (" + offset + ")" if offset else "")


def git(*args, cwd=project):
    try:
        return subprocess.check_output(["git"] + list(args), cwd=cwd,
                                       stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""


branch = git("rev-parse", "--abbrev-ref", "HEAD") or "?"
commit = git("rev-parse", "--short", "HEAD") or "?"
dirty = "dirty" if git("status", "--porcelain") else ""
core = git("rev-parse", "--short", "HEAD", cwd=os.path.join(project, "main", "grbl")) or "?"

content = (
    "/* auto-generated by scripts/build_stamp.py */\n"
    "#pragma once\n"
    "#define BUILD_STAMP  \"%s\"\n"
    "#define BUILD_BRANCH \"%s\"\n"
    "#define BUILD_COMMIT \"%s\"\n"
    "#define BUILD_DIRTY  \"%s\"\n"
    "#define BUILD_CORE   \"%s\"\n" % (stamp, branch, commit, dirty, core)
)

try:
    with open(path, "r", encoding="utf-8") as fh:
        if fh.read() == content:
            raise SystemExit
except (IOError, OSError):
    pass

with open(path, "w", encoding="utf-8") as fh:
    fh.write(content)
