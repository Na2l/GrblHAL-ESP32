#!/usr/bin/env python3
"""Generate main/app_assets.h: PWA manifest, service worker and PNG icons.

Icons come from docs/logo/ so the web UI and the installed app use the same
artwork (icon-only favicon, icon+CNC app icons).
"""
import os

# Runs both standalone and as a PlatformIO pre-script (SCons has no __file__).
try:
    Import("env")                       # noqa: F821 - SCons builtin
    ROOT = env.subst("$PROJECT_DIR")    # noqa: F821
except Exception:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ICONS = [
    ("icon32_png", "docs/logo/icon-32.png"),
    ("icon48_png", "docs/logo/icon-48.png"),
    ("app180_png", "docs/logo/app-180.png"),
    ("app192_png", "docs/logo/app-192.png"),
    ("app512_png", "docs/logo/app-512.png"),
    ("appmask512_png", "docs/logo/app-maskable-512.png"),
]

MANIFEST = r'''{
  "name": "CNC 3018-PRO",
  "short_name": "CNC",
  "description": "grblHAL DLC32 MAX controller UI",
  "start_url": "/",
  "scope": "/",
  "display": "standalone",
  "orientation": "any",
  "background_color": "#0a0f17",
  "theme_color": "#0a0f17",
  "icons": [
    { "src": "/app-192.png", "sizes": "192x192", "type": "image/png" },
    { "src": "/app-512.png", "sizes": "512x512", "type": "image/png" },
    { "src": "/app-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable" }
  ]
}
'''

SW = r'''/* CNC 3018-PRO service worker (installable app support) */
const CACHE = 'cnc-ui-v1';
self.addEventListener('install', e => { self.skipWaiting(); });
self.addEventListener('activate', e => { e.waitUntil(clients.claim()); });
/* network-first: the UI is served by the controller, never cache stale API */
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.pathname.startsWith('/api/')) return;       // live data
  e.respondWith(fetch(e.request).catch(() => caches.match(e.request)));
});
'''


def main():
    out = ["/* Auto-generated by scripts/gen_assets.py - do not edit. */",
           "#ifndef __APP_ASSETS_H__", "#define __APP_ASSETS_H__", ""]
    for name, rel in ICONS:
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            print("WARN missing", rel)
            continue
        data = open(path, "rb").read()
        out.append(f"static const unsigned char {name}[] = {{")
        for i in range(0, len(data), 20):
            out.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
        out.append("};")
        out.append(f"static const unsigned int {name}_len = {len(data)};")
        out.append("")
    out.append('static const char app_manifest_json[] = R"MANIFEST(' + MANIFEST.strip() + ')MANIFEST";')
    out.append("")
    out.append('static const char app_sw_js[] = R"SWJS(' + SW.strip() + ')SWJS";')
    out.append("")
    out.append("#endif")
    with open(os.path.join(ROOT, "main", "app_assets.h"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote main/app_assets.h")


if __name__ == "__main__":
    main()
