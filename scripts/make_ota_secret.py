#!/usr/bin/env python3
"""Create main/ota_secret.h with the OTA password (gitignored, never commit).

    python3 scripts/make_ota_secret.py 'MyStrongPassword'
    python3 scripts/make_ota_secret.py            # generates a random one

The file is included by main/my_machine.h if present, so the password stays
out of the repository. Rebuild + OTA-deploy after changing it.
"""
import os
import secrets
import string
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "main", "ota_secret.h")


def main():
    if len(sys.argv) > 1:
        pw = sys.argv[1]
    else:
        alphabet = string.ascii_letters + string.digits
        pw = "".join(secrets.choice(alphabet) for _ in range(20))
        print("generated password:", pw)
    if not pw:
        sys.exit("password must not be empty")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write('// generated by scripts/make_ota_secret.py - DO NOT COMMIT\n')
        fh.write('#pragma once\n')
        fh.write('#define OTA_PASSWORD "%s"\n' % pw)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
